class MingshuOutputFormatter:
    """
    北斗命數輸出格式化器
    
    確保每個輸出都包含：
    1. raw - 原始數據
    2. explanation - 白話解釋
    3. field_theory - 場論視角
    4. advice - 實用建議
    """
    
    VERSION = "1.0.0"
    
    def format_bazi_output(self, bazi_data: Dict) -> Dict:
        """格式化八字輸出"""
        result = {
            "raw": bazi_data,
            "interpretations": []
        }
        
        # 解讀四柱十神
        pillars = ["年柱", "月柱", "日柱", "時柱"]
        for i, pillar in enumerate(pillars):
            if f"pillar_{i}" in bazi_data or "shishen" in bazi_data:
                # 假設有十神數據
                pass
        
        return result
    
    def format_ziwei_output(self, ziwei_data: Dict) -> Dict:
        """格式化紫微輸出"""
        result = {
            "raw": ziwei_data,
            "star_interpretations": [],
            "sihua_interpretations": [],
            "summary": ""
        }
        
        # 解讀主星
        if "命宮主星" in ziwei_data:
            star = ziwei_data["命宮主星"]
            result["star_interpretations"].append(
                format_star_output(star, "命宮")
            )
        
        # 解讀四化
        if "四化" in ziwei_data:
            for sihua_type, star in ziwei_data["四化"].items():
                gong = ziwei_data.get("星曜宮位", {}).get(star, "")
                result["sihua_interpretations"].append(
                    format_sihua_output(sihua_type, star, gong)
                )
        
        return result
    
    def format_qimen_output(self, qimen_data: Dict) -> Dict:
        """格式化奇門輸出"""
        result = {
            "raw": qimen_data,
            "interpretations": {},
            "summary": ""
        }
        
        # 解讀值使門
        if "duty_men" in qimen_data:
            result["interpretations"]["值使門"] = format_bamen_output(
                qimen_data["duty_men"]
            )
        
        # 解讀各宮
        if "gongs" in qimen_data:
            result["interpretations"]["各宮"] = []
            for gong in qimen_data["gongs"]:
                if "men" in gong:
                    result["interpretations"]["各宮"].append(
                        format_bamen_output(gong["men"], gong.get("position", 0))
                    )
        
        # 當運
        result["interpretations"]["當運"] = format_yun_output(9)
        
        return result
    
    def format_liuren_output(self, liuren_data: Dict) -> Dict:
        """格式化六壬輸出"""
        result = {
            "raw": liuren_data,
            "interpretations": [],
            "summary": ""
        }
        
        # 解讀四課神將
        if "sike" in liuren_data:
            for ke in liuren_data["sike"]:
                if "shenjiang_name" in ke:
                    result["interpretations"].append(
                        format_shenjiang_output(ke["shenjiang_name"])
                    )
        
        return result
    
    def format_fengshui_output(self, fengshui_data: Dict) -> Dict:
        """格式化風水輸出"""
        result = {
            "raw": fengshui_data,
            "interpretations": {},
            "summary": ""
        }
        
        # 當運解讀
        if "current_yun" in fengshui_data:
            result["interpretations"]["當運"] = format_yun_output(
                fengshui_data["current_yun"]
            )
        
        return result


