def get_yao_info(gua_num: int, yao_pos: int) -> Optional[Dict]:
    """獲取爻的完整信息"""
    return YAO_384.get((gua_num, yao_pos))

def get_yao_position_guide(pos: int) -> Optional[Dict]:
    """獲取爻位通則"""
    return YAO_POSITION_GUIDE.get(pos)

def translate_yao(gua_num: int, yao_pos: int) -> str:
    """生成爻的白話翻譯文本"""
    yao = get_yao_info(gua_num, yao_pos)
    guide = get_yao_position_guide(yao_pos)
    
    if not yao:
        return f"未找到第{gua_num}卦第{yao_pos}爻"
    
    return f"""
【{yao['yao']}】{yao['text']}

🗣 白話：{yao['vernacular']}

⚡ 場論：{yao['field']}

🎯 行動：{yao['action']}

📍 爻位：{guide['name']}爻 — {guide['meaning']}，{guide['tendency']}
"""

def generate_yao_report(gua_num: int, yao_pos: int) -> Dict:
    """生成爻的報告格式"""
    yao = get_yao_info(gua_num, yao_pos)
    guide = get_yao_position_guide(yao_pos)
    
    if not yao:
        return {"error": f"未找到第{gua_num}卦第{yao_pos}爻"}
    
    return {
        "gua_num": gua_num,
        "yao_pos": yao_pos,
        "yao_name": yao["yao"],
        "text": yao["text"],
        "vernacular": yao["vernacular"],
        "field": yao["field"],
        "action": yao["action"],
        "position_guide": guide
    }

def get_all_yao_for_gua(gua_num: int) -> List[Dict]:
    """獲取一卦的所有爻"""
    result = []
    for pos in range(1, 7):
        yao = get_yao_info(gua_num, pos)
        if yao:
            result.append({
                "position": pos,
                **yao,
                "guide": get_yao_position_guide(pos)
            })
    return result

